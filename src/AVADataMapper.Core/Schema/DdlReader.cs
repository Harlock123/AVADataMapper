using System.Text;
using Microsoft.SqlServer.TransactSql.ScriptDom;

namespace AVADataMapper.Core.Schema;

/// <summary>
/// Reads a schema from DDL scripts: CREATE TABLE (columns, types, nulls, defaults, identity, primary, unique and foreign
/// keys, checks) and ALTER TABLE … ADD CONSTRAINT. T-SQL goes through Microsoft's own parser (ScriptDom); PostgreSQL and
/// SQLite through a small parser of their CREATE TABLE. Other statements (inserts, indexes, procedures) are skipped.
/// </summary>
public static class DdlReader
{
    public static DatabaseSchema Read(string text, Dialect dialect, string source) =>
        dialect == Dialect.SqlServer ? ReadTsql(text, source) : ReadGeneric(text, dialect, source);

    /// <summary>Which dialect a script is in, from its words: GO, IDENTITY and brackets say SQL Server; SERIAL, GENERATED and :: say PostgreSQL.</summary>
    public static Dialect Guess(string text)
    {
        int tsql = 0, pg = 0, lite = 0;
        if (System.Text.RegularExpressions.Regex.IsMatch(text, @"^\s*GO\s*$", System.Text.RegularExpressions.RegexOptions.Multiline | System.Text.RegularExpressions.RegexOptions.IgnoreCase)) tsql += 3;
        foreach (var (word, score) in new[] { ("IDENTITY(", 2), ("NVARCHAR", 1), ("[dbo]", 2), ("dbo.", 2), ("DATETIME2", 1) })
            if (text.Contains(word, StringComparison.OrdinalIgnoreCase)) tsql += score;
        foreach (var (word, score) in new[] { ("SERIAL", 2), ("GENERATED ALWAYS", 2), ("GENERATED BY DEFAULT", 2), ("::", 2), ("TIMESTAMPTZ", 2), ("BOOLEAN", 1), ("BYTEA", 2) })
            if (text.Contains(word, StringComparison.OrdinalIgnoreCase)) pg += score;
        foreach (var (word, score) in new[] { ("AUTOINCREMENT", 3), ("WITHOUT ROWID", 3), ("INTEGER PRIMARY KEY", 2) })
            if (text.Contains(word, StringComparison.OrdinalIgnoreCase)) lite += score;
        return tsql >= pg && tsql >= lite && tsql > 0 ? Dialect.SqlServer : lite > pg ? Dialect.Sqlite : Dialect.PostgreSql;
    }

    // ───────────────────────────── T-SQL ─────────────────────────────

    private static DatabaseSchema ReadTsql(string text, string source)
    {
        var parser = new TSql170Parser(initialQuotedIdentifiers: true);
        var fragment = parser.Parse(new StringReader(text), out var errors);
        if (errors.Count > 0 && fragment is not TSqlScript { Batches.Count: > 0 })
            throw new FormatException($"The script doesn't parse as T-SQL: line {errors[0].Line}: {errors[0].Message}");
        var schema = new DatabaseSchema { Dialect = Dialect.SqlServer, Source = source };
        var visitor = new TsqlVisitor(schema);
        fragment.Accept(visitor);
        if (schema.Tables.Count == 0 && errors.Count > 0)
            throw new FormatException($"The script doesn't parse as T-SQL: line {errors[0].Line}: {errors[0].Message}");
        return schema;
    }

    private static string Text(TSqlFragment f)
    {
        var sb = new StringBuilder();
        for (var i = f.FirstTokenIndex; i <= f.LastTokenIndex; i++) sb.Append(f.ScriptTokenStream[i].Text);
        return System.Text.RegularExpressions.Regex.Replace(sb.ToString(), @"\s+", " ").Trim();
    }

    private sealed class TsqlVisitor(DatabaseSchema schema) : TSqlFragmentVisitor
    {
        public override void Visit(CreateTableStatement node)
        {
            var name = node.SchemaObjectName;
            var table = new Table { Schema = name.SchemaIdentifier?.Value ?? "dbo", Name = name.BaseIdentifier.Value };
            var ordinal = 0;
            foreach (var c in node.Definition?.ColumnDefinitions ?? [])
            {
                var declared = c.DataType == null ? (c.ComputedColumnExpression != null ? "computed" : "sql_variant") : Text(c.DataType);
                var nullable = c.Constraints.OfType<NullableConstraintDefinition>().FirstOrDefault()?.Nullable ?? true;
                foreach (var u in c.Constraints.OfType<UniqueConstraintDefinition>())
                {
                    if (u.IsPrimaryKey) { table.PrimaryKey.Add(c.ColumnIdentifier.Value); nullable = false; }
                    else table.Uniques.Add([c.ColumnIdentifier.Value]);
                }
                foreach (var fk in c.Constraints.OfType<ForeignKeyConstraintDefinition>())
                    table.ForeignKeys.Add(new ForeignKey(fk.ConstraintIdentifier?.Value ?? $"FK_{table.Name}_{c.ColumnIdentifier.Value}", [c.ColumnIdentifier.Value],
                        Full(fk.ReferenceTableName), fk.ReferencedTableColumns.Count > 0 ? [.. fk.ReferencedTableColumns.Select(r => r.Value)] : []));
                foreach (var ck in c.Constraints.OfType<CheckConstraintDefinition>()) table.Checks.Add(Text(ck.CheckCondition));
                table.Columns.Add(new Column
                {
                    Name = c.ColumnIdentifier.Value, Type = DataType.Parse(declared), Nullable = nullable && c.IdentityOptions == null,
                    Default = c.DefaultConstraint == null ? null : Text(c.DefaultConstraint.Expression), Identity = c.IdentityOptions != null, Ordinal = ++ordinal,
                });
            }
            foreach (var tc in node.Definition?.TableConstraints ?? []) Add(table, tc);
            schema.Tables.Add(table);
        }

        public override void Visit(AlterTableAddTableElementStatement node)
        {
            var table = schema.Table(Full(node.SchemaObjectName));
            if (table == null) return;
            foreach (var tc in node.Definition?.TableConstraints ?? []) Add(table, tc);
        }

        private void Add(Table table, ConstraintDefinition tc)
        {
            switch (tc)
            {
                case UniqueConstraintDefinition u:
                    var cols = u.Columns.Select(x => x.Column.MultiPartIdentifier.Identifiers[^1].Value).ToList();
                    if (u.IsPrimaryKey) { table.PrimaryKey.Clear(); table.PrimaryKey.AddRange(cols); }
                    else table.Uniques.Add(cols);
                    break;
                case ForeignKeyConstraintDefinition fk:
                    table.ForeignKeys.Add(new ForeignKey(fk.ConstraintIdentifier?.Value ?? $"FK_{table.Name}_{table.ForeignKeys.Count + 1}",
                        [.. fk.Columns.Select(x => x.Value)], Full(fk.ReferenceTableName), [.. fk.ReferencedTableColumns.Select(x => x.Value)]));
                    break;
                case CheckConstraintDefinition ck:
                    table.Checks.Add(Text(ck.CheckCondition));
                    break;
            }
            // A primary key's columns don't take nulls, whatever the column said.
            for (var i = 0; i < table.Columns.Count; i++)
                if (table.PrimaryKey.Contains(table.Columns[i].Name, StringComparer.OrdinalIgnoreCase) && table.Columns[i].Nullable)
                    table.Columns[i] = new Column { Name = table.Columns[i].Name, Type = table.Columns[i].Type, Nullable = false, Default = table.Columns[i].Default, Identity = table.Columns[i].Identity, Ordinal = table.Columns[i].Ordinal };
        }

        private static string Full(SchemaObjectName n) => n.SchemaIdentifier != null ? $"{n.SchemaIdentifier.Value}.{n.BaseIdentifier.Value}" : n.BaseIdentifier.Value;
    }

    // ───────────────────────────── PostgreSQL and SQLite ─────────────────────────────

    /// <summary>A token: a word (identifier or keyword, quotes taken off), a string, a number, or punctuation.</summary>
    internal readonly record struct Token(string Text, bool Quoted, bool IsString);

    internal static List<Token> Tokens(string text)
    {
        var list = new List<Token>();
        var i = 0;
        while (i < text.Length)
        {
            var ch = text[i];
            if (char.IsWhiteSpace(ch)) { i++; continue; }
            if (ch == '-' && i + 1 < text.Length && text[i + 1] == '-') { while (i < text.Length && text[i] != '\n') i++; continue; }
            if (ch == '/' && i + 1 < text.Length && text[i + 1] == '*') { var end = text.IndexOf("*/", i + 2, StringComparison.Ordinal); i = end < 0 ? text.Length : end + 2; continue; }
            if (ch is '"' or '`' or '[')
            {
                var close = ch == '[' ? ']' : ch;
                var end = text.IndexOf(close, i + 1);
                if (end < 0) end = text.Length;
                list.Add(new Token(text[(i + 1)..end], true, false));
                i = end + 1;
                continue;
            }
            if (ch == '\'')
            {
                var sb = new StringBuilder();
                i++;
                while (i < text.Length)
                {
                    if (text[i] == '\'' && i + 1 < text.Length && text[i + 1] == '\'') { sb.Append('\''); i += 2; continue; }
                    if (text[i] == '\'') { i++; break; }
                    sb.Append(text[i++]);
                }
                list.Add(new Token(sb.ToString(), false, true));
                continue;
            }
            if (char.IsLetterOrDigit(ch) || ch is '_' or '$' or '.')
            {
                var start = i;
                while (i < text.Length && (char.IsLetterOrDigit(text[i]) || text[i] is '_' or '$' or '.')) i++;
                list.Add(new Token(text[start..i], false, false));
                continue;
            }
            if (ch == ':' && i + 1 < text.Length && text[i + 1] == ':') { list.Add(new Token("::", false, false)); i += 2; continue; }
            list.Add(new Token(ch.ToString(), false, false));
            i++;
        }
        return list;
    }

    private static bool Is(Token t, string word) => !t.Quoted && !t.IsString && t.Text.Equals(word, StringComparison.OrdinalIgnoreCase);

    private static string Join(IEnumerable<Token> tokens)
    {
        var sb = new StringBuilder();
        Token? last = null;
        foreach (var t in tokens)
        {
            var s = t.IsString ? "'" + t.Text.Replace("'", "''") + "'" : t.Quoted ? "\"" + t.Text + "\"" : t.Text;
            // "(" sticks to a function's name (upper(x)), not to an operator or a keyword (amount > (0), x IN (…)).
            var word = last is { } w && !w.IsString && (w.Quoted || w.Text.Length > 0 && (char.IsLetterOrDigit(w.Text[0]) || w.Text[0] == '_'))
                       && !new[] { "AND", "OR", "NOT", "CHECK", "IN", "IS", "LIKE", "BETWEEN" }.Any(k => Is(w, k));
            var tight = last == null || s is ")" or "," or "::" || last.Value.Text is "(" or "::" || (s == "(" && word);
            if (!tight) sb.Append(' ');
            sb.Append(s);
            last = t;
        }
        return sb.ToString();
    }

    private static DatabaseSchema ReadGeneric(string text, Dialect dialect, string source)
    {
        var schema = new DatabaseSchema { Dialect = dialect, Source = source };
        var tokens = Tokens(text);
        var statements = new List<List<Token>>();
        var current = new List<Token>();
        foreach (var t in tokens)
        {
            if (t.Text == ";" && !t.IsString && !t.Quoted) { if (current.Count > 0) statements.Add(current); current = []; }
            else current.Add(t);
        }
        if (current.Count > 0) statements.Add(current);
        foreach (var s in statements)
        {
            if (s.Count > 2 && Is(s[0], "CREATE"))
            {
                var i = 1;
                while (i < s.Count && (Is(s[i], "TEMP") || Is(s[i], "TEMPORARY") || Is(s[i], "UNLOGGED") || Is(s[i], "GLOBAL") || Is(s[i], "LOCAL"))) i++;
                if (i >= s.Count || !Is(s[i], "TABLE")) continue;
                i++;
                if (i + 2 < s.Count && Is(s[i], "IF") && Is(s[i + 1], "NOT") && Is(s[i + 2], "EXISTS")) i += 3;
                var (sch, name) = Name(s, ref i, dialect);
                if (i >= s.Count || s[i].Text != "(") continue;
                var table = new Table { Schema = sch, Name = name };
                foreach (var element in Elements(s, i)) Element(table, element);
                if (table.PrimaryKey.Count == 1 && dialect == Dialect.Sqlite && table.Column(table.PrimaryKey[0]) is { Type.Kind: TypeKind.Integer } pk && pk.Type.Declared.Equals("integer", StringComparison.OrdinalIgnoreCase))
                    Replace(table, pk, identity: true);
                foreach (var key in table.PrimaryKey.ToList())
                    if (table.Column(key) is { Nullable: true } c) Replace(table, c, nullable: false);
                schema.Tables.Add(table);
            }
            else if (s.Count > 4 && Is(s[0], "ALTER") && Is(s[1], "TABLE"))
            {
                var i = 2;
                if (Is(s[i], "ONLY")) i++;
                if (i + 2 < s.Count && Is(s[i], "IF") && Is(s[i + 1], "EXISTS")) i += 2;
                var (sch, name) = Name(s, ref i, dialect);
                var table = schema.Table(sch.Length > 0 ? $"{sch}.{name}" : name);
                if (table == null || i >= s.Count || !Is(s[i], "ADD")) continue;
                Element(table, s.Skip(i + 1).ToList());
            }
        }
        return schema;
    }

    private static (string Schema, string Name) Name(List<Token> s, ref int i, Dialect dialect)
    {
        var parts = new List<string>();
        while (i < s.Count && s[i].Text != "(" && !Is(s[i], "ADD") && !Is(s[i], "AS"))
        {
            if (s[i].Quoted) parts.Add(s[i].Text);
            else parts.AddRange(s[i].Text.Split('.', StringSplitOptions.RemoveEmptyEntries));
            i++;
        }
        var defaultSchema = dialect == Dialect.PostgreSql ? "public" : "";
        return parts.Count switch { 0 => ("", ""), 1 => (defaultSchema, parts[0]), _ => (parts[^2], parts[^1]) };
    }

    /// <summary>The comma-separated elements inside the parentheses that start at <paramref name="open"/>.</summary>
    private static List<List<Token>> Elements(List<Token> s, int open)
    {
        var list = new List<List<Token>>();
        var current = new List<Token>();
        var depth = 0;
        for (var i = open; i < s.Count; i++)
        {
            var t = s[i];
            if (!t.IsString && !t.Quoted && t.Text == "(") { depth++; if (depth == 1) continue; }
            if (!t.IsString && !t.Quoted && t.Text == ")") { depth--; if (depth == 0) { if (current.Count > 0) list.Add(current); break; } }
            if (depth == 1 && !t.IsString && !t.Quoted && t.Text == ",") { list.Add(current); current = []; continue; }
            current.Add(t);
        }
        return list;
    }

    private static List<string> Names(List<Token> e, ref int i)
    {
        var names = new List<string>();
        if (i >= e.Count || e[i].Text != "(") return names;
        i++;
        while (i < e.Count && e[i].Text != ")")
        {
            if (e[i].Text != "," && !Is(e[i], "ASC") && !Is(e[i], "DESC")) names.Add(e[i].Text);
            i++;
        }
        i++;
        return names;
    }

    private static List<Token> Group(List<Token> e, ref int i)
    {
        var inner = new List<Token>();
        if (i >= e.Count || e[i].Text != "(") return inner;
        var depth = 0;
        for (; i < e.Count; i++)
        {
            if (e[i].Text == "(" && !e[i].IsString) depth++;
            if (e[i].Text == ")" && !e[i].IsString) { depth--; if (depth == 0) { i++; break; } }
            if (depth >= 1 && !(depth == 1 && e[i].Text == "(" && inner.Count == 0 && !e[i].IsString)) inner.Add(e[i]);
        }
        return inner;
    }

    private static readonly string[] ConstraintWords = ["CONSTRAINT", "PRIMARY", "UNIQUE", "FOREIGN", "CHECK", "EXCLUDE"];
    private static readonly string[] ColumnConstraintWords = ["NOT", "NULL", "DEFAULT", "PRIMARY", "UNIQUE", "REFERENCES", "CHECK", "CONSTRAINT", "GENERATED", "COLLATE", "AUTOINCREMENT", "IDENTITY"];

    /// <summary>A table element (a column, or a table constraint), or the constraint after ALTER TABLE … ADD.</summary>
    internal static void Element(Table table, List<Token> e)
    {
        if (e.Count == 0) return;
        var i = 0;
        string? constraintName = null;
        if (Is(e[0], "CONSTRAINT")) { constraintName = e.Count > 1 ? e[1].Text : null; i = 2; }
        if (i < e.Count && ConstraintWords.Any(w => Is(e[i], w)) || constraintName != null)
        {
            if (i >= e.Count) return;
            if (Is(e[i], "PRIMARY")) { i += 2; var cols = Names(e, ref i); table.PrimaryKey.Clear(); table.PrimaryKey.AddRange(cols); }
            else if (Is(e[i], "UNIQUE")) { i++; if (i < e.Count && Is(e[i], "KEY")) i++; table.Uniques.Add(Names(e, ref i)); }
            else if (Is(e[i], "FOREIGN"))
            {
                i += 2;
                var cols = Names(e, ref i);
                if (i < e.Count && Is(e[i], "REFERENCES"))
                {
                    i++;
                    var (sch, name) = Name(e, ref i, Dialect.Sqlite);
                    table.ForeignKeys.Add(new ForeignKey(constraintName ?? $"fk_{table.Name}_{table.ForeignKeys.Count + 1}", cols, sch.Length > 0 ? $"{sch}.{name}" : name, Names(e, ref i)));
                }
            }
            else if (Is(e[i], "CHECK")) { i++; table.Checks.Add(Join(Group(e, ref i))); }
            return;
        }
        if (Is(e[0], "LIKE")) return;
        var colName = e[0].Text;
        i = 1;
        var typeTokens = new List<Token>();
        var depth = 0;
        while (i < e.Count && (depth > 0 || !ColumnConstraintWords.Any(w => Is(e[i], w))))
        {
            if (e[i].Text == "(") depth++;
            if (e[i].Text == ")") depth--;
            typeTokens.Add(e[i]);
            i++;
        }
        var declared = typeTokens.Count == 0 ? "" : Join(typeTokens).Replace(" (", "(", StringComparison.Ordinal);
        var nullable = true;
        string? @default = null;
        var identity = declared.StartsWith("serial", StringComparison.OrdinalIgnoreCase) || declared.StartsWith("bigserial", StringComparison.OrdinalIgnoreCase) || declared.StartsWith("smallserial", StringComparison.OrdinalIgnoreCase);
        while (i < e.Count)
        {
            if (Is(e[i], "CONSTRAINT")) { i += 2; continue; }
            if (Is(e[i], "NOT") && i + 1 < e.Count && Is(e[i + 1], "NULL")) { nullable = false; i += 2; continue; }
            if (Is(e[i], "NULL")) { i++; continue; }
            if (Is(e[i], "PRIMARY")) { i += 2; while (i < e.Count && (Is(e[i], "ASC") || Is(e[i], "DESC"))) i++; table.PrimaryKey.Clear(); table.PrimaryKey.Add(colName); nullable = false; continue; }
            if (Is(e[i], "AUTOINCREMENT")) { identity = true; i++; continue; }
            if (Is(e[i], "UNIQUE")) { table.Uniques.Add([colName]); i++; continue; }
            if (Is(e[i], "GENERATED"))
            {
                // GENERATED ALWAYS|BY DEFAULT AS IDENTITY [(…)], or GENERATED ALWAYS AS (expr) STORED (computed).
                var j = i + 1;
                while (j < e.Count && !Is(e[j], "AS")) j++;
                if (j + 1 < e.Count && Is(e[j + 1], "IDENTITY")) { identity = true; nullable = false; i = j + 2; if (i < e.Count && e[i].Text == "(") Group(e, ref i); }
                else { i = j + 1; Group(e, ref i); if (i < e.Count && (Is(e[i], "STORED") || Is(e[i], "VIRTUAL"))) i++; }
                continue;
            }
            if (Is(e[i], "DEFAULT"))
            {
                i++;
                var d = new List<Token>();
                if (i < e.Count && e[i].Text == "(") { d.Add(e[i]); var g = Group(e, ref i); d.AddRange(g); d.Add(new Token(")", false, false)); }
                else
                    while (i < e.Count && !ColumnConstraintWords.Any(w => Is(e[i], w))) d.Add(e[i++]);
                @default = Join(d);
                if (@default.Contains("nextval(", StringComparison.OrdinalIgnoreCase)) identity = true;
                continue;
            }
            if (Is(e[i], "REFERENCES"))
            {
                i++;
                var (sch, name) = Name(e, ref i, Dialect.Sqlite);
                table.ForeignKeys.Add(new ForeignKey($"fk_{table.Name}_{colName}", [colName], sch.Length > 0 ? $"{sch}.{name}" : name, Names(e, ref i)));
                continue;
            }
            if (Is(e[i], "CHECK")) { i++; table.Checks.Add(Join(Group(e, ref i))); continue; }
            if (Is(e[i], "COLLATE")) { i += 2; continue; }
            i++;
        }
        table.Columns.Add(new Column { Name = colName, Type = DataType.Parse(declared.Length > 0 ? declared : "text"), Nullable = nullable && !identity, Default = @default, Identity = identity, Ordinal = table.Columns.Count + 1 });
    }

    private static void Replace(Table table, Column c, bool? nullable = null, bool? identity = null)
    {
        var i = table.Columns.IndexOf(c);
        table.Columns[i] = new Column { Name = c.Name, Type = c.Type, Nullable = nullable ?? c.Nullable, Default = c.Default, Identity = identity ?? c.Identity, Ordinal = c.Ordinal };
        if (identity == true) table.Columns[i] = new Column { Name = c.Name, Type = c.Type, Nullable = false, Default = c.Default, Identity = true, Ordinal = c.Ordinal };
    }
}
